// Adds a YouTube music video to an album. Checks the link with YouTube first, so you see the
// real video title and channel before anything is saved.
// Usage:  node db/add-video.mjs "Model" "https://www.youtube.com/watch?v=VIDEO_ID"
// Then apply db/seed-videos.sql to the database.
import { appendFileSync, existsSync, writeFileSync } from 'node:fs';

const [albumTitle, link] = process.argv.slice(2);
if (!albumTitle || !link) {
  console.error('Usage: node db/add-video.mjs "<album title>" "<youtube url>"');
  process.exit(1);
}

const idMatch = link.match(/(?:youtu\.be\/|[?&]v=|\/embed\/|\/shorts\/)([A-Za-z0-9_-]{11})/);
if (!idMatch) {
  console.error('Could not find a YouTube video id in that link.');
  process.exit(1);
}
const id = idMatch[1];
const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;

const res = await fetch(
  `https://www.youtube.com/oembed?format=json&url=${encodeURIComponent(`https://www.youtube.com/watch?v=${id}`)}`
);
if (!res.ok) {
  console.error(`YouTube answered ${res.status}: the video is missing, private, or has embedding turned off.`);
  process.exit(1);
}
const info = await res.json();
console.log(`Found: "${info.title}" on channel "${info.author_name}"`);

const file = new URL('./seed-videos.sql', import.meta.url);
if (!existsSync(file)) writeFileSync(file, '-- Generated by db/add-video.mjs\n', 'utf8');
appendFileSync(
  file,
  `INSERT INTO video (album_id, title, youtube_id) SELECT id, ${quote(info.title)}, ${quote(id)} FROM album WHERE title = ${quote(albumTitle)} ON CONFLICT DO NOTHING;\n`,
  'utf8'
);
console.log('Added to db/seed-videos.sql');
