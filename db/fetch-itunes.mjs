// Fetches cover art, track lists and 30-second previews from the iTunes Search API
// and writes db/seed-itunes.sql.
// Usage (backend running on :8080):  node db/fetch-itunes.mjs
import { writeFileSync } from 'node:fs';

const API = process.env.API_URL ?? 'http://localhost:8080';
const norm = (s) => s.toLowerCase().replace(/\(.*?\)|\[.*?\]/g, '').replace(/[^a-z0-9]+/g, ' ').trim();
const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// iTunes allows roughly 20 requests a minute, so space the calls out and retry on errors.
async function itunes(path, params) {
  const url = new URL(`https://itunes.apple.com/${path}`);
  for (const [k, v] of Object.entries(params)) url.searchParams.set(k, v);
  for (let attempt = 1; attempt <= 3; attempt++) {
    const res = await fetch(url);
    if (res.ok) {
      await sleep(3200);
      return (await res.json()).results ?? [];
    }
    await sleep(5000 * attempt);
  }
  throw new Error(`iTunes request failed: ${url}`);
}

const albums = await (await fetch(`${API}/api/albums`)).json();
const lines = ['-- Generated by db/fetch-itunes.mjs (iTunes Search API)'];
const missing = [];

for (const a of albums) {
  const results = await itunes('search', { term: `${a.artist} ${a.title}`, entity: 'album', limit: 10 });
  const hit =
    results.find((r) => norm(r.collectionName) === norm(a.title) && norm(r.artistName) === norm(a.artist)) ??
    results.find((r) => norm(r.collectionName).startsWith(norm(a.title)) && norm(r.artistName).includes(norm(a.artist)));

  if (!hit) {
    missing.push(a.title);
    continue;
  }

  lines.push(`UPDATE album SET cover_url = ${quote(hit.artworkUrl100.replace('100x100bb', '600x600bb'))} WHERE id = ${a.id};`);

  const items = await itunes('lookup', { id: hit.collectionId, entity: 'song', limit: 60 });
  const tracks = items
    .filter((r) => r.wrapperType === 'track' && r.previewUrl)
    .sort((x, y) => (x.discNumber - y.discNumber) || (x.trackNumber - y.trackNumber))
    .slice(0, 25);

  lines.push(`DELETE FROM track WHERE album_id = ${a.id};`);
  if (tracks.length) {
    const values = tracks.map(
      (t, i) => `(${a.id}, ${i + 1}, ${quote(t.trackName)}, ${t.trackTimeMillis ?? 'NULL'}, ${quote(t.previewUrl)})`
    );
    lines.push(`INSERT INTO track (album_id, track_number, title, duration_ms, preview_url) VALUES\n  ${values.join(',\n  ')};`);
  }
  console.log(`${a.title}: ${hit.collectionName} (${hit.artistName}), ${tracks.length} previews`);
}

writeFileSync(new URL('./seed-itunes.sql', import.meta.url), lines.join('\n') + '\n', 'utf8');
console.log('Wrote db/seed-itunes.sql');
if (missing.length) console.warn('No match for:', missing.join(', '));
