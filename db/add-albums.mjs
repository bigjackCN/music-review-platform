// Adds extra albums to the database and fetches covers, track lists and 30-second previews
// from the iTunes Search API. Writes db/seed-albums-extra.sql.
// Usage:  node db/add-albums.mjs      (no backend needed)
import { writeFileSync } from 'node:fs';

// Edit this list to add more albums. `genre` is what the genre filter shows.
const ALBUMS = [
  { title: 'The Long Run', artist: 'Eagles', genre: 'Rock', year: 1979,
    match: /^the long run/i, artistMatch: /eagles/i },
  { title: 'Model', artist: 'Li Ronghao (李荣浩)', genre: 'Mandopop', year: 2013,
    term: '李荣浩 模特', countries: ['cn', 'tw', 'us'], match: /模特|model/i, artistMatch: /李荣浩|李榮浩|li ronghao/i },
  { title: 'Unplugged', artist: 'Leessang', genre: 'Hip Hop', year: 2012,
    collectionId: 1698495155, countries: ['us', 'kr'] },
  { title: 'Taxi Driver', artist: 'Dynamic Duo', genre: 'Hip Hop', year: 2004,
    match: /taxi driver/i, artistMatch: /dynamic ?duo|다이나믹 ?듀오/i, countries: ['us', 'kr'] },
  { title: "Fever's End: Part 2", artist: 'Tablo', genre: 'Hip Hop',
    collectionId: 1339457592, countries: ['us', 'kr'] },
  { title: 'Deadman', artist: 'KUN', genre: 'Pop',
    collectionId: 1812117264, countries: ['us', 'cn', 'mz'] },
  // Bandcamp-only release: no iTunes preview, plays through Bandcamp's official embed instead.
  { title: 'Asian River', artist: 'Hualun (花伦)', genre: 'Post-Rock', year: 2010,
    bandcampId: 2797230705, coverUrl: 'https://f4.bcbits.com/img/a0493747800_5.jpg' },
];

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// iTunes allows roughly 20 requests a minute, so space the calls out and retry on errors.
async function itunes(path, params) {
  const url = new URL(`https://itunes.apple.com/${path}`);
  for (const [k, v] of Object.entries(params)) url.searchParams.set(k, v);
  for (let attempt = 1; attempt <= 3; attempt++) {
    const res = await fetch(url);
    if (res.ok) {
      await sleep(3200);
      return (await res.json()).results ?? [];
    }
    await sleep(5000 * attempt);
  }
  throw new Error(`iTunes request failed: ${url}`);
}

const trackRows = (items) =>
  items
    .filter((r) => r.wrapperType === 'track' && r.previewUrl)
    .sort((x, y) => (x.discNumber - y.discNumber) || (x.trackNumber - y.trackNumber))
    .slice(0, 25);

async function findOnItunes(a) {
  for (const country of a.countries ?? ['us']) {
    if (a.collectionId) {
      const items = await itunes('lookup', { id: a.collectionId, entity: 'song', limit: 60, country });
      const collection = items.find((r) => r.wrapperType === 'collection');
      if (collection) return { collection, tracks: trackRows(items), country };
    } else {
      const results = await itunes('search', {
        term: a.term ?? `${a.artist} ${a.title}`, entity: 'album', limit: 10, country,
      });
      const collection = results.find((r) => a.match.test(r.collectionName) && a.artistMatch.test(r.artistName));
      if (collection) {
        const items = await itunes('lookup', { id: collection.collectionId, entity: 'song', limit: 60, country });
        return { collection, tracks: trackRows(items), country };
      }
    }
  }
  return null;
}

const lines = ['-- Generated by db/add-albums.mjs'];
const problems = [];

for (const a of ALBUMS) {
  const where = `title = ${quote(a.title)} AND artist = ${quote(a.artist)}`;
  let cover = a.coverUrl ?? null;
  let year = a.year ?? null;
  let tracks = [];

  if (!a.bandcampId) {
    const found = await findOnItunes(a);
    if (!found) {
      problems.push(`${a.title}: not found on iTunes, added without cover or previews`);
    } else {
      cover = found.collection.artworkUrl100.replace('100x100bb', '600x600bb');
      year ??= new Date(found.collection.releaseDate).getUTCFullYear();
      tracks = found.tracks;
      console.log(`${a.title}: ${found.collection.collectionName} by ${found.collection.artistName} [${found.country}], ${tracks.length} previews`);
    }
  } else {
    console.log(`${a.title}: Bandcamp release ${a.bandcampId}`);
  }

  lines.push(
    `INSERT INTO album (title, artist, release_year, genre) SELECT ${quote(a.title)}, ${quote(a.artist)}, ${year ?? 'NULL'}, ${quote(a.genre)} WHERE NOT EXISTS (SELECT 1 FROM album WHERE ${where});`
  );
  if (cover) lines.push(`UPDATE album SET cover_url = ${quote(cover)} WHERE ${where};`);
  if (a.bandcampId) lines.push(`UPDATE album SET bandcamp_id = ${a.bandcampId} WHERE ${where};`);
  lines.push(`DELETE FROM track WHERE album_id IN (SELECT id FROM album WHERE ${where});`);
  if (tracks.length) {
    const values = tracks.map(
      (t, i) => `(${i + 1}, ${quote(t.trackName)}, ${t.trackTimeMillis ?? 'NULL'}, ${quote(t.previewUrl)})`
    );
    lines.push(
      `INSERT INTO track (album_id, track_number, title, duration_ms, preview_url)\nSELECT a.id, v.n, v.t, v.d, v.u FROM album a,\n  (VALUES\n  ${values.join(',\n  ')}\n  ) AS v(n, t, d, u)\nWHERE a.${where.replace(' AND artist', ' AND a.artist')};`
    );
  }
}

writeFileSync(new URL('./seed-albums-extra.sql', import.meta.url), lines.join('\n') + '\n', 'utf8');
console.log('Wrote db/seed-albums-extra.sql');
for (const p of problems) console.warn('Check:', p);
